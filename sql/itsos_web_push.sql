-- Background web push, no personal student data. Service-role access only.
create schema if not exists private;
create table if not exists public.itsos_push_subscriptions (
 id uuid primary key default gen_random_uuid(),
 endpoint text not null unique,
 p256dh text not null, auth_secret text not null,
 client_token_hash text not null,
 preference text not null check (preference in ('all','limited')),
 team_ids bigint[] not null default '{}',
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.itsos_push_events (
 id bigint generated by default as identity primary key,
 source text not null,
 event_key text not null unique,
 title text not null, body text not null, href text not null default '/',
 team_ids bigint[] not null default '{}',
 created_at timestamptz not null default now(),
 claimed_at timestamptz,
 delivered_at timestamptz
);
create table if not exists public.itsos_push_deliveries (
 event_id bigint not null references public.itsos_push_events(id) on delete cascade,
 subscription_id uuid not null references public.itsos_push_subscriptions(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key(event_id,subscription_id)
);
alter table public.itsos_push_subscriptions enable row level security;
alter table public.itsos_push_events enable row level security;
alter table public.itsos_push_deliveries enable row level security;
revoke all on table public.itsos_push_subscriptions,public.itsos_push_events,public.itsos_push_deliveries from anon,authenticated;
grant all on table public.itsos_push_subscriptions,public.itsos_push_events,public.itsos_push_deliveries to service_role;
grant usage, select on all sequences in schema public to service_role;
create index if not exists itsos_push_events_queued on public.itsos_push_events(delivered_at,claimed_at);
create index if not exists itsos_push_subs_by_pref on public.itsos_push_subscriptions(preference);

create or replace function private.itsos_queue_announcement_push()
returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.is_active is not true then return new; end if;
 if TG_OP='UPDATE' and (new.title,new.body,new.is_active,new.updated_at) is not distinct from
                           (old.title,old.body,old.is_active,old.updated_at) then return new; end if;
 insert into public.itsos_push_events(source,event_key,title,body,href)
 values ('platform', concat('announcement-',new.id,'-',extract(epoch from coalesce(new.updated_at,new.created_at,now()))),
         left(new.title,120), left(new.body,240), '/')
 on conflict(event_key) do nothing;
 return new;
end;$$;
drop trigger if exists itsos_push_announcement on public.urgent_announcements;
create trigger itsos_push_announcement after insert or update on public.urgent_announcements
for each row execute function private.itsos_queue_announcement_push();

create or replace function private.itsos_queue_match_push()
returns trigger language plpgsql security definer set search_path='' as $$
declare v_kind text; v_title text; v_body text; v_href text;
begin
 if TG_OP='INSERT' then return new; end if;
 if new.is_finished=true and (old.is_finished is distinct from true or new.home_score is distinct from old.home_score or new.away_score is distinct from old.away_score) then
   v_kind='result';v_title='Risultato finale';
   v_body=concat('Risultato ',coalesce(new.home_score,0),' - ',coalesce(new.away_score,0));
 elsif new.status='live' and old.status is distinct from new.status then
   v_kind='live';v_title='Partita iniziata';v_body='La partita è in corso';
 elsif new.scheduled_start is distinct from old.scheduled_start or new.venue_id is distinct from old.venue_id then
   v_kind='schedule';v_title='Partita aggiornata';v_body='Sono cambiati orario o campo';
 else return new;
 end if;
 v_href=concat('/?sport=',new.sport_id,'&match=',new.id);
 insert into public.itsos_push_events(source,event_key,title,body,href,team_ids)
 values('team', concat('match-',new.id,'-',v_kind,'-',extract(epoch from clock_timestamp())),
  v_title, v_body,v_href,array[new.home_team_id,new.away_team_id])
 on conflict(event_key) do nothing;
 return new;
end;$$;
drop trigger if exists itsos_push_match_change on public.matches;
create trigger itsos_push_match_change after update on public.matches for each row execute function private.itsos_queue_match_push();

-- Keys and dispatch secrets are stored ONLY in Vault and read by the service role.
-- Create secrets separately in production; never commit their values.
create or replace function public.itsos_push_runtime_config()
returns jsonb language sql stable security definer set search_path='' as $$
 select jsonb_build_object(
  'public', (select decrypted_secret from vault.decrypted_secrets where name='itsos_vapid_public' limit 1),
  'private',(select decrypted_secret from vault.decrypted_secrets where name='itsos_vapid_private' limit 1),
  'subject',(select decrypted_secret from vault.decrypted_secrets where name='itsos_vapid_subject' limit 1),
  'cron',(select decrypted_secret from vault.decrypted_secrets where name='itsos_push_cron_secret' limit 1)
 );
$$;
revoke all on function public.itsos_push_runtime_config() from public,anon,authenticated;
grant execute on function public.itsos_push_runtime_config() to service_role;

create or replace function public.itsos_claim_push_events(p_limit int default 15)
returns setof public.itsos_push_events language sql volatile security definer set search_path='' as $$
 update public.itsos_push_events e set claimed_at=now()
 where e.id in (
  select x.id from public.itsos_push_events x
  where x.delivered_at is null and (x.claimed_at is null or x.claimed_at < now()-interval '5 minutes')
  order by x.id for update skip locked limit greatest(1,least(p_limit,25))
 ) returning e.*;
$$;
revoke all on function public.itsos_claim_push_events(int) from public,anon,authenticated;
grant execute on function public.itsos_claim_push_events(int) to service_role;
